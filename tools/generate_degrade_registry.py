"""Registry and metadata writers for synthetic degradation manifolds.

Split out of :mod:`tools.generate_degrade`: creates the ``manifold_registry.db``
schema, commits the per-sample records, and writes the manifold's
``dataset_info.yaml``, ``README.md`` and ``classes.txt``.
"""

from __future__ import annotations

import json
import sqlite3
import time
from contextlib import closing
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from core.registry import initialize_registry
from degrade import parse_profile

_SAMPLES_DDL = """
            CREATE TABLE IF NOT EXISTS samples (
                id INTEGER PRIMARY KEY,
                name TEXT UNIQUE NOT NULL,
                source TEXT NOT NULL,
                task TEXT NOT NULL,
                split TEXT NOT NULL,
                hash TEXT,
                perceptual_hash TEXT,
                img_format TEXT,
                img_size_bytes INTEGER,
                target_size_bytes INTEGER,
                mask_size_bytes INTEGER DEFAULT 0,
                is_hardlinked INTEGER DEFAULT 0,
                reject_code TEXT,
                audit_trail TEXT,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
        """

# ``audit_events`` comes from core.registry (keyed by ``registry.id``); the
# event row looks the id up by the sample name the registry row was just
# written under.
_AUDIT_EVENT_SQL = """
    INSERT INTO audit_events (sample_id, event_type, event_data)
    SELECT id, ?, ? FROM registry WHERE name = ?
"""

# Both tables share the same column layout for a synthesized sample.
_UPSERT_SQL = (
    """
    INSERT OR REPLACE INTO samples (
        name, source, task, split, img_format, img_size_bytes, target_size_bytes
    ) VALUES (?, ?, ?, ?, ?, ?, ?)
    """,
    """
    INSERT OR REPLACE INTO registry (
        name, source, task, split, img_format, img_size_bytes, target_size_bytes
    ) VALUES (?, ?, ?, ?, ?, ?, ?)
    """,
)


def init_synthetic_registry(db_path: Path) -> None:
    """Initialize manifold_registry.db schema for synthetic manifold."""
    initialize_registry(db_path).close()
    with closing(sqlite3.connect(db_path)) as conn:
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute(_SAMPLES_DDL)
        conn.commit()


def commit_records(db_path: Path, records: list[dict[str, Any]]) -> None:
    """Insert every synthesized sample into ``samples``, ``registry`` and ``audit_events``."""
    with closing(sqlite3.connect(db_path)) as conn:
        for r in records:
            row = (
                r["name"],
                r["source"],
                r["task"],
                r["split"],
                r["img_format"],
                r["img_size"],
                r["target_size"],
            )
            for sql in _UPSERT_SQL:
                conn.execute(sql, row)
            conn.execute(
                _AUDIT_EVENT_SQL,
                ("degradation_synthesis", json.dumps(r["label_payload"]), r["name"]),
            )
        conn.commit()


@dataclass(frozen=True)
class ManifoldDescription:
    """What a synthetic manifold was built from, for its metadata files."""

    output_path: Path
    source_path: Path
    profile_expr: str
    intensity: str
    seed: int


def write_metadata(desc: ManifoldDescription, records: list[dict[str, Any]]) -> int:
    """Write dataset_info.yaml, README.md and classes.txt; return the sample count."""
    total_written = len(records)
    info_yaml = {
        "dataset_name": desc.output_path.name,
        "task": "restoration",
        "dataset_type": "vision_paired",
        "synthetic": True,
        "base_source": str(desc.source_path.name),
        "degradation_profile": desc.profile_expr,
        "degradation_steps": parse_profile(desc.profile_expr, intensity=desc.intensity)
        .config()["steps"],
        "intensity": desc.intensity,
        "seed": desc.seed,
        "total_samples": total_written,
        "train_samples": sum(1 for r in records if r["split"] == "train"),
        "val_samples": sum(1 for r in records if r["split"] == "val"),
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    (desc.output_path / "dataset_info.yaml").write_text(
        json.dumps(info_yaml, indent=2), encoding="utf-8"
    )

    split_counts = (
        f"Train: {info_yaml['train_samples']:,}, Val: {info_yaml['val_samples']:,}"
    )
    readme_content = f"""# {desc.output_path.name}

> Synthesized Restoration Dataset Manifold generated by LemGendary Dataset Compiler (Phase 6).

## Dataset Summary

- **Task**: Image Restoration & Enhancement
- **Base Ground Truth**: `{desc.source_path.name}`
- **Degradation Profile**: `{desc.profile_expr}`
- **Intensity**: `{desc.intensity}`
- **Base Seed**: `{desc.seed}`
- **Total Samples**: {total_written:,} ({split_counts})
- **Format**: WebP (Images: q=92, Targets: q=95)

## Parameter Supervision

Every sample in `images/` has its clean ground truth in `targets/` and exact parameter descriptor in `labels/<split>/<name>.json`.
"""
    (desc.output_path / "README.md").write_text(readme_content, encoding="utf-8")
    (desc.output_path / "classes.txt").write_text("restoration\n", encoding="utf-8")
    return total_written
