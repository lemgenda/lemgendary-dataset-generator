"""Direct Preference Optimization (DPO / ORPO) Preference Pair Generator.

Constructs paired preference examples (prompt, chosen, rejected) for post-SFT alignment:
- `chosen`: Grounded, concise response with correct epistemic tag, zero emojis, and exact bounds.
- `rejected`: Generated by injecting controlled negative patterns (hallucination, emoji violation,
  incomplete diagnostic protocol, or uncalibrated overconfidence).

Enables training models to resist hallucination and enforce authoritative compliance.
"""

from __future__ import annotations

import re
from typing import Any

_EMOJI_PATTERN = re.compile(
    r"[\U00010000-\U0010ffff\u2600-\u26FF\u2700-\u27BF\uFE0F]",
    flags=re.UNICODE,
)


class DPOSynthesizer:
    """Generates (chosen, rejected) preference pairs for preference optimization."""

    NEGATIVE_STRATEGIES: tuple[str, ...] = (
        "uncalibrated_overconfidence",
        "hallucinated_flag",
        "protocol_omission",
        "verbose_padding",
    )

    def __init__(self) -> None:
        pass

    def build_preference_pair(
        self,
        prompt: str,
        chosen_response: str,
        strategy: str = "uncalibrated_overconfidence",
        system_prompt: str | None = None,
    ) -> dict[str, Any]:
        """Synthesize a DPO preference record from a verified chosen response."""
        chosen_clean = _EMOJI_PATTERN.sub("", chosen_response).strip()
        rejected = self._create_negative_response(chosen_clean, strategy)

        record = {
            "prompt": _EMOJI_PATTERN.sub("", prompt).strip(),
            "chosen": chosen_clean,
            "rejected": rejected,
            "strategy": strategy,
        }
        if system_prompt:
            record["system"] = _EMOJI_PATTERN.sub("", system_prompt).strip()
        return record

    def validate_preference_pair(self, pair: dict[str, Any]) -> bool:
        """Confirm that pair has required keys and chosen differs from rejected."""
        if not all(k in pair for k in ("prompt", "chosen", "rejected")):
            return False
        return str(pair["chosen"]).strip() != str(pair["rejected"]).strip()

    def _create_negative_response(self, chosen: str, strategy: str) -> str:
        """Mutate a valid response into a plausible but flawed rejected alternative."""
        if strategy == "uncalibrated_overconfidence":
            # Strip epistemic uncertainty tags and replace with ungrounded certainty
            res = re.sub(r"\[(CONFIRMED|PROBABLE|ILLUSTRATIVE)\]\s*", "", chosen)
            return f"I guarantee 100% certainty that this will always work without issues. {res}"

        if strategy == "hallucinated_flag":
            # Inject fake, non-existent flags
            return (
                f"{chosen}\n\n"
                f"You can also pass `--force-all-unsafe` and `--skip-validation-gates`."
            )

        if strategy == "protocol_omission":
            # Strip diagnostic triage stages and directly command action
            lines = chosen.splitlines()
            remediation_lines = [ln for ln in lines if ln.strip().startswith("-") or "Run " in ln]
            return "Just execute this command right away:\n" + "\n".join(remediation_lines[:2])

        # Default: verbose_padding (adds repetitive boilerplate)
        return (
            "Here is an overview of everything you could possibly want to know about this.\n"
            "First of all, in general computing, things can happen.\n"
            f"{chosen}\n\n"
            "I hope this exceptionally long explanation was helpful to you in every way!"
        )
